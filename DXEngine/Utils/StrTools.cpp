uint32_t StrTools::ue1_strihash(const std::string_view& str)
{
	static uint32_t table[256];
	static bool made = false;
	if (!made)
	{
		for (uint32_t i = 0; i < 256; i++)
		{
			uint32_t c = i << 24;
			for (int j = 0; j < 8; j++)
				c = (c & 0x80000000u) ? (c << 1) ^ 0x04C11DB7u : (c << 1);
			table[i] = c;
		}
		made = true;
	}
	uint32_t hash = 0;
	for (char ch : str)
	{
		// A character of DXEngine's strings is one byte; the original's are
		// two, the second 0 here.
		uint16_t c = (uint8_t)ch;
		if (c >= 'a' && c <= 'z')
			c -= 'a' - 'A';
		hash = (hash >> 8) ^ table[(c & 0xFF) ^ (hash & 0xFF)];
		hash = (hash >> 8) ^ table[(c >> 8) ^ (hash & 0xFF)];
	}
	return hash;
}

bool StrTools::equals_ignore_case(const std::string_view& str1, const std::string_view& str2)
{
	if (str1.size() != str2.size())
		return false;
	for (size_t i = 0, length = str1.size(); i < length; i++)
	{
		if (stricmptable[(uint8_t)str1[i]] != stricmptable[(uint8_t)str2[i]])
			return false;
	}
	return true;
}

int32_t StrTools::ue1_atoi(const std::string_view& str)
{
	size_t pos = 0;
	while (pos < str.size() && (str[pos] == ' ' || (str[pos] >= '\t' && str[pos] <= '\r')))
		pos++;
	bool negative = false;
	if (pos < str.size() && (str[pos] == '+' || str[pos] == '-'))
		negative = str[pos++] == '-';
	// Held at one past an int's top as it is read: no sum can overflow
	int64_t value = 0;
	for (; pos < str.size() && str[pos] >= '0' && str[pos] <= '9'; pos++)
		value = std::min(value * 10 + (str[pos] - '0'), (int64_t)INT32_MAX + 1);
	if (negative)
		value = -value;
	return (int32_t)std::clamp(value, (int64_t)INT32_MIN, (int64_t)INT32_MAX);
}

bool StrTools::startswith(const std::string_view& str, const std::string_view& cmp, bool ignoreCase)
{
	if (str.size() < cmp.size())
		return false;

	if (ignoreCase)
		return StrTools::equals_ignore_case(str.substr(0, cmp.size()), cmp);

	return str.starts_with(cmp);
}

size_t StrTools::find_first_of_any(const std::string& str, const std::string& characters)
{
	for (size_t idx = 0 ; idx < str.size() ; idx++)
	{
		for (const auto& c : characters)
			if (c == str[idx])
				return idx;
	}

	return std::string::npos;
}

std::string StrTools::float_text(double value)
{
	if (std::isnan(value))
		return std::signbit(value) ? "-1.#IND00" : "1.#QNAN0";
	if (std::isinf(value))
		return value < 0 ? "-1.#INF00" : "1.#INF00";

	// Every digit, exactly, to forty decimals: far past any float's sixth
	char buf[400];
	std::snprintf(buf, sizeof(buf), "%.40f", value);
	std::string text(buf);
	bool negative = text[0] == '-';
	if (negative)
		text.erase(0, 1);
	size_t point = text.find('.');
	std::string whole = text.substr(0, point);
	std::string decimals = text.substr(point + 1);

	// Six decimals, the seventh's 5 or more rounding up, carried leftward
	bool roundUp = decimals[6] >= '5';
	decimals.resize(6);
	if (roundUp)
	{
		std::string number = whole + decimals;
		int i = (int)number.size() - 1;
		while (i >= 0 && number[i] == '9')
			number[i--] = '0';
		if (i >= 0)
			number[i]++;
		else
			number.insert(number.begin(), '1');
		whole = number.substr(0, number.size() - 6);
		decimals = number.substr(number.size() - 6);
	}
	return (negative ? "-" : "") + whole + "." + decimals;
}
